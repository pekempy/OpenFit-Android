/** Look up the Health Connect exercise type Int id for a given display label.
 * Falls back to EXERCISE_TYPE_OTHER_WORKOUT for custom/unrecognised labels. */
fun exerciseTypeIdForLabel(label: String): Int =
    HC_EXERCISE_TYPES.find { it.label.equals(label, ignoreCase = true) }?.id
        ?: ExerciseSessionRecord.EXERCISE_TYPE_OTHER_WORKOUT

